package store

import (
	"context"
	"fmt"
	"os"

	"github.com/jackc/pgx/v5/pgxpool"
)

var DB *pgxpool.Pool

func ConnectPostresql() {
	var err error

	DB_URL := os.Getenv("DB_URL")

	if len(DB_URL) == 0 {
		fmt.Println("[ERROR] DB_URL is not set in .env file")
		os.Exit(1)
	}

	DB, err = pgxpool.New(
		context.Background(),
		DB_URL,
	)

	if err != nil {
		fmt.Println("[ERROR] Connect database error")
		fmt.Println("Error: ", err)
		os.Exit(1)
	}

	fmt.Println("[INFO] Database connected")
}

func CreateTables() {
	_, err := DB.Exec(
		context.Background(),
		`
		CREATE TABLE IF NOT EXISTS users (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			username TEXT NOT NULL UNIQUE,
			name TEXT NOT NULL,
			password TEXT NOT NULL,
			created_at TIMESTAMP NOT NULL DEFAULT NOW()
		);
		`,
	)

	if err != nil {
		fmt.Println("[ERROR] Create 'users' table error")
		fmt.Println("Error: ", err)
		os.Exit(1)
	}

	_, err = DB.Exec(
		context.Background(),
		`
		CREATE TABLE IF NOT EXISTS refresh_tokens (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
			token TEXT NOT NULL,
			expires_at TIMESTAMP NOT NULL
		);
		`,
	)

	if err != nil {
		fmt.Println("[ERROR] Create 'refresh_tokens' table error")
		fmt.Println("Error: ", err)

		os.Exit(1)
	}

	_, err = DB.Exec(
		context.Background(),
		`
		CREATE TABLE IF NOT EXISTS meshflows (
		    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
		    username TEXT NOT NULL,
		    content TEXT NOT NULL,
		    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
		);
		`,
	)

	if err != nil {
		fmt.Println("[ERROR] Create 'meshflows' table error")
		fmt.Println("Error: ", err)

		os.Exit(1)
	}

	_, err = DB.Exec(
		context.Background(),
		`
		CREATE TABLE IF NOT EXISTS comments (
		    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		    meshflow_id BIGINT NOT NULL REFERENCES meshflows(id) ON DELETE CASCADE,
		    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
		    username TEXT NOT NULL,
		    content TEXT NOT NULL,
		    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
		);
		`,
	)

	if err != nil {
		fmt.Println("[ERROR] Create 'comments' table error")
		fmt.Println("Error: ", err)

		os.Exit(1)
	}

	_, err = DB.Exec(
		context.Background(),
		`
		CREATE TABLE IF NOT EXISTS likes (
		    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		    meshflow_id BIGINT NOT NULL REFERENCES meshflows(id) ON DELETE CASCADE,
		    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
		    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
		    UNIQUE (meshflow_id, user_id)
		);
		`,
	)

	if err != nil {
		fmt.Println("[ERROR] Create 'likes' table error")
		fmt.Println("Error: ", err)

		os.Exit(1)
	}

	_, err = DB.Exec(
		context.Background(),
		`
		CREATE TABLE IF NOT EXISTS meshwrites (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
			username TEXT NOT NULL,
			title TEXT NOT NULL,
			content TEXT NOT NULL,
			created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
		);
		`,
	)

	if err != nil {
		fmt.Println("[ERROR] Create 'meshwrites' table error")
		fmt.Println("Error: ", err)

		os.Exit(1)
	}

	_, err = DB.Exec(
		context.Background(),
		`
		CREATE TABLE IF NOT EXISTS meshwrites_saves (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
			meshwrite_id BIGINT NOT NULL REFERENCES meshwrites(id) ON DELETE CASCADE,
			UNIQUE (user_id, meshwrite_id)
		);
		`,
	)

	if err != nil {
		fmt.Println("[ERROR] Create 'meshwrites_saves' table error")
		fmt.Println("Error: ", err)
		os.Exit(1)
	}

	_, err = DB.Exec(
		context.Background(),
		`
		CREATE TABLE IF NOT EXISTS nodes (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			name TEXT NOT NULL UNIQUE,
			description TEXT NOT NULL,
			created_at TIMESTAMPTZ DEFAULT NOW()
		);
		`,
	)

	if err != nil {
		fmt.Println("[ERROR] Create 'nodes' table error")
		fmt.Println("Error: ", err)

		os.Exit(1)
	}

	_, err = DB.Exec(
		context.Background(),
		`
		CREATE TABLE IF NOT EXISTS nodes_members (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			node_id BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
			user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
			username TEXT NOT NULL,
			role TEXT NOT NULL,
			joined_at TIMESTAMPTZ DEFAULT NOW(),
			UNIQUE (node_id, user_id)
		);
		`,
	)

	if err != nil {
		fmt.Println("[ERROR] Create 'nodes_members' table error")
		fmt.Println("Error: ", err)

		os.Exit(1)
	}

	// Older installs of nodes_members had no node_id and declared username
	// UNIQUE, which kept a user from joining more than one node. Bring the
	// table up to the current shape; safe to run on every startup.
	_, err = DB.Exec(
		context.Background(),
		`
		DO $$
		BEGIN
			ALTER TABLE nodes_members
				DROP CONSTRAINT IF EXISTS nodes_members_username_key;

			IF NOT EXISTS (
				SELECT 1
				FROM information_schema.columns
				WHERE table_schema = 'public'
				  AND table_name = 'nodes_members'
				  AND column_name = 'node_id'
			) THEN
				ALTER TABLE nodes_members
					ADD COLUMN node_id BIGINT REFERENCES nodes(id) ON DELETE CASCADE;

				-- Legacy rows have no node reference, so they cannot be
				-- mapped to one.
				DELETE FROM nodes_members
				WHERE node_id IS NULL;

				ALTER TABLE nodes_members
					ALTER COLUMN node_id SET NOT NULL;
			END IF;

			IF NOT EXISTS (
				SELECT 1
				FROM pg_constraint
				WHERE conname = 'nodes_members_node_id_user_id_key'
			) THEN
				ALTER TABLE nodes_members
					ADD CONSTRAINT nodes_members_node_id_user_id_key
					UNIQUE (node_id, user_id);
			END IF;
		END
		$$;
		`,
	)

	if err != nil {
		fmt.Println("[ERROR] Migrate 'nodes_members' constraints error")
		fmt.Println("Error: ", err)

		os.Exit(1)
	}

	_, err = DB.Exec(
		context.Background(),
		`
		CREATE TABLE IF NOT EXISTS node_posts (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			node_id BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
			user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
			username TEXT NOT NULL,
			title TEXT NOT NULL,
			content TEXT NOT NULL,
			created_at TIMESTAMPTZ DEFAULT NOW()
		);
		`,
	)

	if err != nil {
		fmt.Println("[ERROR] Create 'node_posts' table error")
		fmt.Println("Error: ", err)

		os.Exit(1)
	}

	fmt.Println("[INFO] All Tables created")
}
