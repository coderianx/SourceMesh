package store

import (
	"context"
	"fmt"
	"os"

	"github.com/jackc/pgx/v5/pgxpool"
)

var DB *pgxpool.Pool

func ConnectPostresql() {
	var err error

	DB_URL := os.Getenv("DB_URL")

	if len(DB_URL) == 0 {
		fmt.Println("[ERROR] DB_URL is not set in .env file")
		os.Exit(1)
	}

	DB, err = pgxpool.New(
		context.Background(),
		DB_URL,
	)

	if err != nil {
		fmt.Println("[ERROR] Connect database error")
		fmt.Println("Error: ", err)
		os.Exit(1)
	}

	fmt.Println("[INFO] Database connected")
}

func CreateTables() {
	_, err := DB.Exec(
		context.Background(),
		`
		CREATE TABLE IF NOT EXISTS users (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			username TEXT NOT NULL UNIQUE,
			name TEXT NOT NULL,
			password TEXT NOT NULL,
			created_at TIMESTAMP NOT NULL DEFAULT NOW()
		);
		`,
	)

	if err != nil {
		fmt.Println("[ERROR] Create 'users' table error")
		fmt.Println("Error: ", err)
		os.Exit(1)
	}

	_, err = DB.Exec(
		context.Background(),
		`
		CREATE TABLE IF NOT EXISTS refresh_tokens (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
			token TEXT NOT NULL,
			expires_at TIMESTAMP NOT NULL
		);
		`,
	)

	if err != nil {
		fmt.Println("[ERROR] Create 'refresh_tokens' table error")
		fmt.Println("Error: ", err)

		os.Exit(1)
	}

	_, err = DB.Exec(
		context.Background(),
		`
		CREATE TABLE IF NOT EXISTS meshflows (
		    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
		    username TEXT NOT NULL,
		    content TEXT NOT NULL,
		    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
		);
		`,
	)

	if err != nil {
		fmt.Println("[ERROR] Create 'meshflows' table error")
		fmt.Println("Error: ", err)

		os.Exit(1)
	}

	_, err = DB.Exec(
		context.Background(),
		`
		CREATE TABLE IF NOT EXISTS comments (
		    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		    meshflow_id BIGINT NOT NULL REFERENCES meshflows(id) ON DELETE CASCADE,
		    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
		    username TEXT NOT NULL,
		    content TEXT NOT NULL,
		    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
		);
		`,
	)

	if err != nil {
		fmt.Println("[ERROR] Create 'comments' table error")
		fmt.Println("Error: ", err)

		os.Exit(1)
	}

}
